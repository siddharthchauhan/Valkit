def deep_get(mapping: Mapping[str, Any], path: str, default: Any = None) -> Any:
    """Look up ``a.b.c`` in nested mappings, returning ``default`` if absent."""
    current: Any = mapping
    for part in path.split("."):
        if not isinstance(current, Mapping) or part not in current:
            return default
        current = current[part]
    return current


_SECRET_KEYS = {"password", "secret", "token", "api_key", "apikey", "credential", "otp"}


def redact(value: Any) -> Any:
    """Recursively replace secret-looking values before they reach a log.

    The audit trail is a permanent record. Anything that looks like the second
    component of an electronic signature must never enter it.
    """
    if isinstance(value, Mapping):
        return {
            k: ("***REDACTED***" if str(k).lower() in _SECRET_KEYS else redact(v))
            for k, v in value.items()
        }
    if isinstance(value, (list, tuple)):
        return [redact(v) for v in value]
    return value
