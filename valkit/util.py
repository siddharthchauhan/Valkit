"""Primitives shared by every ValKit module: canonical serialisation, hashing,
time and identifier generation.

Everything that ends up in an audit trail, a hash chain or a generated
document is serialised through :func:`canonical_json` so that the same logical
record always produces the same bytes, and therefore the same SHA-256. Byte
stability is what makes the evidence chain verifiable years later on a
different machine.
"""

