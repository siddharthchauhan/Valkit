_SLUG_RE = re.compile(r"[^a-z0-9]+")


def slugify(text: str, max_length: int = 64) -> str:
    slug = _SLUG_RE.sub("-", text.strip().lower()).strip("-")
    return slug[:max_length] or "item"


def new_id(prefix: str, entropy: Callable[[], str] | None = None) -> str:
    """Generate a prefixed identifier.

    ``entropy`` is injectable so a deterministic sequence can be supplied in
    tests; the default is a UUID4 suffix.
    """
    suffix = entropy() if entropy is not None else uuid.uuid4().hex[:12]
    return f"{prefix}-{suffix}"


