# --------------------------------------------------------------------------
# Time
# --------------------------------------------------------------------------


class Clock:
    """Source of UTC timestamps.

    Injected rather than called directly so that every artefact ValKit
    produces can be regenerated byte-for-byte in a test.
    """

    def now(self) -> _dt.datetime:  # pragma: no cover - interface
        raise NotImplementedError

    def now_iso(self) -> str:
        return format_utc(self.now())


class SystemClock(Clock):
    """Wall-clock UTC."""

    def now(self) -> _dt.datetime:
        return _dt.datetime.now(_dt.timezone.utc)


class FrozenClock(Clock):
    """Deterministic clock for tests and reproducible regeneration.

    Each call advances by ``step`` seconds so that ordered events keep a
    strictly increasing timestamp without becoming non-deterministic.
    """

    def __init__(self, start: str | _dt.datetime = "2026-01-01T00:00:00Z", step: float = 1.0):
        self._t = parse_utc(start) if isinstance(start, str) else start.astimezone(_dt.timezone.utc)
        self._step = step

    def now(self) -> _dt.datetime:
        current = self._t
        self._t = self._t + _dt.timedelta(seconds=self._step)
        return current


def utc_now() -> _dt.datetime:
    return _dt.datetime.now(_dt.timezone.utc)


def format_utc(value: _dt.datetime) -> str:
    """Render a datetime as a Zulu ISO-8601 string with second precision.

    21 CFR 11.50(a)(2) requires the signed record to show the date and time of
    signing; ValKit always records and displays UTC so that an inspector never
    has to reason about the signer's local offset.
    """
    if value.tzinfo is None:
        value = value.replace(tzinfo=_dt.timezone.utc)
    value = value.astimezone(_dt.timezone.utc).replace(microsecond=0)
    return value.strftime("%Y-%m-%dT%H:%M:%SZ")


def parse_utc(value: str) -> _dt.datetime:
    """Parse an ISO-8601 timestamp, accepting a trailing ``Z``."""
    text = value.strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    parsed = _dt.datetime.fromisoformat(text)
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=_dt.timezone.utc)
    return parsed.astimezone(_dt.timezone.utc)


